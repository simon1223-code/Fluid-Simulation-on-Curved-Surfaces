#!/usr/bin/env python3
"""Taylor--Green-vortex entry point for the face-based 2D Clebsch solver.

This experiment prescribes face Clebsch samples on ``[0, 2*pi]^2`` from

    u_x = sin(x) cos(y),       u_y = -cos(x) sin(y),

which is generated by ``psi = sin(x) sin(y)`` using
``u = (partial_y psi, -partial_x psi)``.  At face centroids, the shared solver
sets ``lambda=(x,y)`` and ``mu=(u_x,u_y)``, reconstructs a normal edge flux,
and projects it to the discrete divergence-free, zero-boundary-flux space.
Because the centroid TPFA gradient is not affine-exact on this mesh, the
resulting discrete initial velocity is a projected approximation to the
analytic Taylor--Green field; the program reports that initial error.

All spatial discretization, SSPRK3 transport, recharting, diagnostics, and
visualization are provided by ``clebsch_euler_2d.py`` so the TGV and perturbed
experiments cannot drift into different algorithms.
"""

import clebsch_euler_2d as solver


def main():
    solver.main(
        fixed_initial_condition=solver.TAYLOR_GREEN,
        description=__doc__,
    )


if __name__ == "__main__":
    main()
